from fastapi import FastAPI, Depends,HTTPException
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.future import select
from contextlib import asynccontextmanager
from typing import Optional,List
from schemas import CourseCreate,CourseResponse
from database import engine, Base, get_db
import models 
from schemas import CourseUpdate

# This tells FastAPI to create the database tables when the app starts
@asynccontextmanager
async def lifespan(app: FastAPI):
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    yield

app = FastAPI(title='Course Management API', version='1.0', lifespan=lifespan)

# ... (your existing @app.get('/') and @app.post('/api/courses/') routes stay the same for now)

@app.get("/")
def root():
    return {'message':'API running'}

